const DAY = 86_400_000;
const HOUR = 3_600_000;
const anchor = Date.parse("2026-08-18T16:00:00Z");

const isoBefore = (amount: number, unit = HOUR) => new Date(anchor - amount * unit).toISOString();

function seededWave(
  length: number,
  start: number,
  drift: number,
  volatility: number,
  startTime = Date.parse("2024-01-02T00:00:00Z"),
  step = 7 * DAY,
): SeriesPoint[] {
  let value = start;
  return Array.from({ length }, (_, index) => {
    const noise = Math.sin(index * 1.81) * volatility + Math.cos(index * 0.47) * volatility * 0.45;
    value = Math.max(1, value + drift + noise);
    return {
      timestamp: new Date(startTime + index * step).toISOString(),
      value: Number(value.toFixed(2)),
      secondary: Number(Math.max(value, start + index * drift * 1.18).toFixed(2)),
      tertiary: Number((15 + Math.sin(index / 4) * 11 + Math.cos(index / 7) * 4).toFixed(2)),
    };
  });
}

